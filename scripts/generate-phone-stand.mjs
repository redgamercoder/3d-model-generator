#!/usr/bin/env node
// Generates models/phone-stand.stl — an angled phone stand with a charging
// cable gap. Same dimensions as the "Phone Stand" preset in the web editor.
// Units are millimeters, Z is up, the model rests on Z = 0.

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const triangles = [];

// Axis-aligned box of size [sx, sy, sz], rotated rotXDeg degrees about its own
// X axis, then centered at [cx, cy, cz].
function box([sx, sy, sz], [cx, cy, cz], rotXDeg = 0) {
  const hx = sx / 2, hy = sy / 2, hz = sz / 2;
  const corners = [
    [-hx, -hy, -hz], [hx, -hy, -hz], [hx, hy, -hz], [-hx, hy, -hz],
    [-hx, -hy, hz], [hx, -hy, hz], [hx, hy, hz], [-hx, hy, hz],
  ];

  const rad = (rotXDeg * Math.PI) / 180;
  const cos = Math.cos(rad), sin = Math.sin(rad);
  const p = corners.map(([x, y, z]) => [
    x + cx,
    y * cos - z * sin + cy,
    y * sin + z * cos + cz,
  ]);

  // Counter-clockwise quads viewed from outside.
  const quads = [
    [0, 3, 2, 1], // bottom
    [4, 5, 6, 7], // top
    [0, 1, 5, 4], // front  (-y)
    [2, 3, 7, 6], // back   (+y)
    [0, 4, 7, 3], // left   (-x)
    [1, 2, 6, 5], // right  (+x)
  ];
  for (const [a, b, c, d] of quads) {
    triangles.push([p[a], p[b], p[c]], [p[a], p[c], p[d]]);
  }
}

// --- Phone stand ------------------------------------------------------------

box([90, 70, 6], [0, 0, 3]);             // base plate
box([90, 6, 80], [0, 14, 39], -20);      // backrest, leaning back 20°
box([32, 6, 22], [-29, -28, 14]);        // front lip, left
box([32, 6, 22], [29, -28, 14]);         // front lip, right
// 26 mm gap between the lips for a charging cable.

// --- Binary STL writer -------------------------------------------------------

function normal([a, b, c]) {
  const u = [b[0] - a[0], b[1] - a[1], b[2] - a[2]];
  const v = [c[0] - a[0], c[1] - a[1], c[2] - a[2]];
  const n = [
    u[1] * v[2] - u[2] * v[1],
    u[2] * v[0] - u[0] * v[2],
    u[0] * v[1] - u[1] * v[0],
  ];
  const len = Math.hypot(...n) || 1;
  return n.map((x) => x / len);
}

const buffer = Buffer.alloc(84 + triangles.length * 50);
buffer.write('phone stand - generated by 3d-model-generator', 0, 'ascii');
buffer.writeUInt32LE(triangles.length, 80);

let offset = 84;
for (const tri of triangles) {
  for (const vec of [normal(tri), ...tri]) {
    buffer.writeFloatLE(vec[0], offset);
    buffer.writeFloatLE(vec[1], offset + 4);
    buffer.writeFloatLE(vec[2], offset + 8);
    offset += 12;
  }
  offset += 2; // attribute byte count
}

const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'models');
mkdirSync(outDir, { recursive: true });
const outPath = join(outDir, 'phone-stand.stl');
writeFileSync(outPath, buffer);

const zs = triangles.flat().map((p) => p[2]);
console.log(`Wrote ${outPath}`);
console.log(`${triangles.length} triangles, height ${Math.min(...zs).toFixed(2)}..${Math.max(...zs).toFixed(2)} mm`);
